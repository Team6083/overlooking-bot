/**
 * Writes api/openapi.yaml from the zod schemas in src/web/schemas.ts.
 *   npm run openapi          # regenerate
 *   npm run openapi -- --check  # exit 1 if the committed file is stale
 */
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';
import { stringify } from 'yaml';
import { buildOpenApiDocument } from '../web/openapi';

export const OPENAPI_PATH = join(__dirname, '..', '..', 'api', 'openapi.yaml');

export function renderOpenApi(): string {
    return '# Generated by `npm run openapi` from src/web/schemas.ts. Do not edit by hand.\n'
        + stringify(buildOpenApiDocument(), { aliasDuplicateObjects: false });
}

if (require.main === module) {
    const rendered = renderOpenApi();
    if (process.argv.includes('--check')) {
        let current = '';
        try { current = readFileSync(OPENAPI_PATH, 'utf8'); } catch { /* missing counts as stale */ }
        if (current !== rendered) {
            console.error('api/openapi.yaml is out of date; run `npm run openapi`.');
            process.exit(1);
        }
    } else {
        writeFileSync(OPENAPI_PATH, rendered);
        console.log(`Wrote ${OPENAPI_PATH}`);
    }
}
